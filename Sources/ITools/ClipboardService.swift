import AppKit
import Combine
import IToolsCore

final class ClipboardService: ObservableObject {
    @Published var entries: [ClipEntry] = []
    @Published var snippets: [Snippet] = []
    @Published var enabled: Bool = false { didSet { UserDefaults.standard.set(enabled, forKey: "clipboard.enabled"); configure() } }
    @Published var filter = ""
    @Published var group = "全部"
    @Published var maxCount = 300
    @Published var retentionDays = 30
    @Published var excludedApps = "com.agilebits.onepassword7,com.1password.1password,com.bitwarden.desktop,com.apple.keychainaccess"
    private var timer: Timer?
    private var changeCount = NSPasteboard.general.changeCount
    private let saveQueue = DispatchQueue(label: "itools.clipboard.storage", qos: .utility)
    private var stack: [ClipEntry] = []
    @Published var stackCount = 0
    var policy: HistoryPolicy { HistoryPolicy(maxCount: maxCount, retentionDays: retentionDays) }
    var groups: [String] { ["全部", "收藏"] + Array(Set(entries.map(\.group).filter { !$0.isEmpty })).sorted() }
    var visible: [ClipEntry] {
        entries.filter { entry in
            (group == "全部" || (group == "收藏" && entry.pinned) || entry.group == group) &&
            (filter.isEmpty || entry.text.localizedCaseInsensitiveContains(filter) || entry.source.localizedCaseInsensitiveContains(filter))
        }
    }
    init() {
        maxCount = UserDefaults.standard.object(forKey: "clipboard.maxCount") as? Int ?? 300
        retentionDays = UserDefaults.standard.object(forKey: "clipboard.retention") as? Int ?? 30
        excludedApps = UserDefaults.standard.string(forKey: "clipboard.exclusions") ?? excludedApps
        entries = policy.prune(Storage.load([ClipEntry].self, "clipboard.json", fallback: []))
        snippets = Storage.load([Snippet].self, "snippets.json", fallback: [])
        enabled = UserDefaults.standard.bool(forKey: "clipboard.enabled")
    }
    func start() { configure() }
    private func configure() {
        timer?.invalidate(); timer = nil
        changeCount = NSPasteboard.general.changeCount
        guard enabled else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }
    func stop() { timer?.invalidate(); timer = nil }
    private func poll() {
        let pb = NSPasteboard.general
        guard changeCount != pb.changeCount else { return }
        changeCount = pb.changeCount
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "未知应用"
        let blocked = excludedApps.split(separator: ",").map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
        guard !blocked.contains(source.lowercased()) else { return }
        let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        guard !(pb.types ?? []).contains(where: { sensitive.contains($0.rawValue) }) else { return }
        guard !(pb.pasteboardItems ?? []).contains(where: { item in item.types.contains { sensitive.contains($0.rawValue) } }) else { return }
        let entry: ClipEntry
        if let files = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty,
           let data = try? JSONEncoder().encode(files.map(\.absoluteString)) {
            entry = ClipEntry(kind: .files, text: files.map(\.lastPathComponent).joined(separator: "\n"), source: source,
                              payload: [.init(type: "com.itools.file-list", data: data)])
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: { pb.availableType(from: [$0]) != nil }), let data = pb.data(forType: type) {
            guard data.count <= 10 * 1024 * 1024 else { return }
            entry = ClipEntry(kind: .image, text: "图片 · " + bytes(UInt64(data.count)), source: source, payload: [.init(type: type.rawValue, data: data)])
        } else if let text = pb.string(forType: .string), !text.isEmpty {
            let parts = [NSPasteboard.PasteboardType.string, .rtf, .html].compactMap { type -> ClipRepresentation? in
                guard let data = pb.data(forType: type) else { return nil }
                return .init(type: type.rawValue, data: data)
            }
            entry = ClipEntry(kind: .text, text: text, source: source, payload: parts)
        } else { return }
        guard entry.byteCount <= 10 * 1024 * 1024 else { return }
        entries = policy.adding(entry, to: entries); persist()
    }
    @discardableResult func copy(_ entry: ClipEntry, plain: Bool = false, paste: Bool = false, to pb: NSPasteboard = .general) -> Bool {
        if paste && pb.name == NSPasteboard.general.name {
            return AppFocus.shared.paste(prepare: { self.copy(entry, plain: plain) })
        }
        pb.clearContents()
        let success: Bool
        if plain && entry.kind == .text { success = pb.setString(entry.text, forType: .string) }
        else if entry.kind == .files, let data = entry.payload.first?.data,
                let paths = try? JSONDecoder().decode([String].self, from: data) {
            let urls = paths.compactMap(URL.init(string:)).filter { $0.isFileURL }
            success = !urls.isEmpty && pb.writeObjects(urls as [NSURL])
        } else {
            var wrote = false
            for part in entry.payload { if pb.setData(part.data, forType: .init(part.type)) { wrote = true } }
            if entry.kind == .text, pb.string(forType: .string) == nil { wrote = pb.setString(entry.text, forType: .string) || wrote }
            success = wrote
        }
        guard success else { NoticeCenter.shared.report(UserFacingError("未能写入剪贴板，请重新复制原始内容。")); return false }
        guard pb.name == NSPasteboard.general.name else { return true }
        changeCount = pb.changeCount
        NoticeCenter.shared.success("已复制到剪贴板")
        return true
    }
    func pin(_ entry: ClipEntry) {
        guard let i = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[i].pinned.toggle(); persist()
    }
    func assignGroup(_ entry: ClipEntry) {
        guard let value = Panels.text("分组名称（留空可移出分组）", initial: entry.group),
              let i = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        let name = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !["全部", "收藏"].contains(name) else { NoticeCenter.shared.report(UserFacingError("这个分组名称已被系统使用。")); return }
        entries[i].group = name; persist()
    }
    func delete(_ entry: ClipEntry) { entries.removeAll { $0.id == entry.id }; persist() }
    func clear() {
        guard Panels.confirm("清空所有剪贴板历史？", detail: "收藏也会删除。此操作无法撤销；不会删除原始文件。", action: "清空") else { return }
        entries = []; stack = []; stackCount = 0; persist()
    }
    func enqueue(_ entry: ClipEntry) { stack.append(entry); stackCount = stack.count; NoticeCenter.shared.success("已加入连续粘贴队列") }
    func pasteNext() {
        guard let entry = stack.first else { NoticeCenter.shared.success("连续粘贴队列为空"); return }
        AppFocus.shared.paste(prepare: { self.copy(entry) }) { submitted in
            guard submitted, self.stack.first?.id == entry.id else { return }
            self.stack.removeFirst(); self.stackCount = self.stack.count
        }
    }
    func saveSettings() {
        UserDefaults.standard.set(maxCount, forKey: "clipboard.maxCount")
        UserDefaults.standard.set(retentionDays, forKey: "clipboard.retention")
        UserDefaults.standard.set(excludedApps, forKey: "clipboard.exclusions")
        entries = policy.prune(entries); persist()
    }
    func persist() {
        let snapshot = entries
        saveQueue.async { do { try Storage.save(snapshot, "clipboard.json") } catch { NoticeCenter.shared.report(error) } }
    }
    func flush() { saveQueue.sync {} }
    func saveSnippet(title: String, body: String, group: String) {
        guard !title.trimmingCharacters(in: .whitespaces).isEmpty, !body.isEmpty else { return }
        snippets.append(Snippet(title: title, body: body, group: group))
        NoticeCenter.shared.perform { try Storage.save(snippets, "snippets.json") }
    }
    func removeSnippet(_ id: UUID) { snippets.removeAll { $0.id == id }; NoticeCenter.shared.perform { try Storage.save(snippets, "snippets.json") } }
    @discardableResult func useSnippet(_ snippet: Snippet, paste: Bool) -> Bool {
        let expanded = snippet.expanded(clipboard: NSPasteboard.general.string(forType: .string) ?? "")
        let prepare = {
            guard copyText(expanded) else { NoticeCenter.shared.report(UserFacingError("未能复制短语，请重试。")); return false }
            self.changeCount = NSPasteboard.general.changeCount; return true
        }
        if paste { return AppFocus.shared.paste(prepare: prepare) }
        let copied = prepare(); if copied { NoticeCenter.shared.success("已复制短语") }; return copied
    }
    func exportHistory() {
        guard let url = Panels.save(name: "iTools-剪贴板.json", types: ["json"]) else { return }
        NoticeCenter.shared.perform { try JSONEncoder().encode(entries).write(to: url, options: .atomic) }
    }
    func importHistory() {
        guard let url = Panels.chooseFiles(types: ["json"], multiple: false).first else { return }
        NoticeCenter.shared.perform {
            let size = try url.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0
            guard size <= 150 * 1024 * 1024 else { throw UserFacingError("导入文件超过 150 MB。") }
            let imported = try JSONDecoder().decode([ClipEntry].self, from: Data(contentsOf: url))
            guard imported.count <= 5000, imported.allSatisfy({ $0.byteCount <= 10 * 1024 * 1024 }) else { throw UserFacingError("条目过多或单项超过 10 MB。") }
            var seen = Set<String>()
            entries = policy.prune((entries + imported).sorted { $0.date > $1.date }.filter { seen.insert($0.fingerprint).inserted })
            persist(); NoticeCenter.shared.success("已合并导入剪贴板记录")
        }
    }
}
